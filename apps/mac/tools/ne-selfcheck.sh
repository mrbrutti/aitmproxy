#!/usr/bin/env bash
# Runner for the Network Extension's in-file self-checks (spec
# docs/superpowers/specs/2026-10-31-ne-claim-rule-design.md, D5 and CR-AC7).
#
# The Extension (apps/mac/Extension) has no SwiftPM test target: build.sh compiles
# Extension/Sources/*.swift straight with swiftc. Its tests are the checks of
# `enum HandoffSelfCheck` (Extension/Sources/FlowHandoff.swift) and of the
# `#if DEBUG extension HandoffSelfCheck` blocks beside the code they test
# (ProviderRules.swift, RuleReconciler.swift), all compiled only under `DEBUG`;
# `HandoffSelfCheck.run()` lists every group and returns one `FAIL ...` line per broken
# check and an empty array when everything holds. Before this script the only way to
# run them was a driver typed into a terminal by hand. This script is that driver,
# committed.
#
# Usage: tools/ne-selfcheck.sh [mac-dir]   (default: the apps/mac that holds this script)
#
#   NE_SELFCHECK_SCRATCH   where the driver, module cache and binary are written
#                          (default: $HOME/Library/Developer/Aitmproxy/ne-selfcheck,
#                          outside the repo like build.sh's scratch). The Claude sandbox
#                          cannot write under ~/Library/Developer; run it there as
#                          NE_SELFCHECK_SCRATCH="$TMPDIR/ne-selfcheck" tools/ne-selfcheck.sh
#
# Exit codes:
#   0  every check holds; prints "PASS: NE handoff self-check"
#   1  at least one check failed; every "FAIL ..." line is printed verbatim
#   2  the self-check could not be built or run: mac-dir has no
#      Extension/Sources/FlowHandoff.swift, the scratch dir is not writable, or swiftc
#      failed (its output is printed)
#
# What is compiled: every Extension/Sources/*.swift EXCEPT Sources/main.swift, plus a
# generated driver main.swift. The real main.swift is the system-extension entry point:
# it calls NEProvider.startSystemExtensionMode() and parks in dispatchMain(), so it would
# never return, and two main.swift files in one module is a compile error anyway. The
# driver is the module's entry point instead: it calls HandoffSelfCheck.run(), prints the
# lines, and exits.
#
# The DEBUG define is passed as the single token `-DDEBUG`, matching the spec's command
# line; swiftc accepts either spelling. Everything the compiler writes goes under the
# scratch dir (-module-cache-path).
set -euo pipefail
export LC_ALL=C

mac_dir=${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}
sources_dir="$mac_dir/Extension/Sources"
if [ ! -f "$sources_dir/FlowHandoff.swift" ]; then
  echo "FAIL ne-selfcheck: $sources_dir/FlowHandoff.swift not found (pass the apps/mac directory as the first argument)" >&2
  exit 2
fi

scratch=${NE_SELFCHECK_SCRATCH:-$HOME/Library/Developer/Aitmproxy/ne-selfcheck}
if ! mkdir -p "$scratch/ModuleCache" 2>/dev/null; then
  echo "FAIL ne-selfcheck: cannot create scratch dir $scratch (set NE_SELFCHECK_SCRATCH to a writable path)" >&2
  exit 2
fi

# One subdirectory per invocation: two sessions sharing the scratch root (the default,
# or one $TMPDIR) must never overwrite each other's driver or binary mid-build, or a
# gate could report another tree's result. ModuleCache stays shared (content-addressed).
run=$(mktemp -d "$scratch/run.XXXXXX") || { echo "FAIL ne-selfcheck: cannot create a run dir under $scratch" >&2; exit 2; }
trap 'rm -rf "$run"' EXIT
driver="$run/main.swift"
cat > "$driver" <<'EOF'
// Generated by apps/mac/tools/ne-selfcheck.sh; never part of the shipped extension.
import Foundation

let failures = HandoffSelfCheck.run()
for line in failures { print(line) }
if failures.isEmpty {
    print("PASS: NE handoff self-check")
    exit(0)
}
print("FAIL: NE handoff self-check (\(failures.count) failing check(s))")
exit(1)
EOF

# build.sh compiles "$ext/Sources/"*.swift (top level only); take that same set minus
# main.swift. (A read loop, not mapfile: /bin/bash on macOS is 3.2.)
sources=()
while IFS= read -r f; do sources+=("$f"); done < <(find "$sources_dir" -maxdepth 1 -name '*.swift' ! -name 'main.swift' | sort)
if [ "${#sources[@]}" -eq 0 ]; then
  echo "FAIL ne-selfcheck: no Swift sources in $sources_dir" >&2
  exit 2
fi

bin="$run/AitmproxyNESelfCheck"
if ! xcrun swiftc \
    -sdk "$(xcrun --show-sdk-path --sdk macosx)" \
    -target "$(uname -m)-apple-macos26.0" \
    -DDEBUG \
    -framework NetworkExtension \
    -module-name AitmproxyNESelfCheck \
    -module-cache-path "$scratch/ModuleCache" \
    -o "$bin" \
    "${sources[@]}" "$driver"; then
  echo "FAIL ne-selfcheck: swiftc failed; the self-check binary was not built" >&2
  exit 2
fi

set +e
"$bin"
status=$?
set -e
exit "$status"
