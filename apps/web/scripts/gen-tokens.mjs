// Generates src/styles/tokens.css from docs/design/tokens.json.
// tokens.json is the single source of truth (docs/design/operator-ui-foundation.md §2);
// this file is the web surface's mapping of it: :root holds light values, [data-theme=dark]
// the dark ones, and prefers-color-scheme picks the default when no theme is pinned.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../../docs/design/tokens.json');
const out = resolve(here, '../src/styles/tokens.css');
const t = JSON.parse(readFileSync(src, 'utf8'));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const isToken = (n) => n && typeof n === 'object' && '$value' in n;

function walk(node, path, fn) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (isToken(v)) fn([...path, k], v.$value);
    else if (v && typeof v === 'object') walk(v, [...path, k], fn);
  }
}

const light = [];
const dark = [];
const shared = [];

// --color-<group>-<name>[-fg|-bg]
walk(t.color, ['color'], (p, v) => {
  const name = '--' + p.map(kebab).join('-');
  const pair = (mode, list) => {
    const m = v[mode];
    if (typeof m === 'string') list.push([name, m]);
    else {
      list.push([`${name}-fg`, m.fg]);
      list.push([`${name}-bg`, m.bg]);
    }
  };
  pair('light', light);
  pair('dark', dark);
});

// typography
for (const [k, v] of Object.entries(t.typography.family)) {
  if (k.startsWith('$')) continue;
  shared.push([`--font-${kebab(k)}`, v.$value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ')]);
}
walk(t.typography.size, ['font-size'], (p, v) => shared.push(['--' + p.map(kebab).join('-'), v]));
walk(t.typography.weight, ['font-weight'], (p, v) => shared.push(['--' + p.map(kebab).join('-'), String(v)]));
walk(t.typography.lineHeight, ['line-height'], (p, v) => shared.push(['--' + p.map(kebab).join('-'), String(v)]));

// space / size / radius
walk(t.space, ['space'], (p, v) => shared.push(['--' + p.join('-'), v]));
walk(t.size, ['size'], (p, v) => shared.push(['--' + p.map(kebab).join('-'), v]));
// size.icon carries inline/toolbar variants outside $value
shared.push(['--size-icon-inline', t.size.icon.inline]);
shared.push(['--size-icon-toolbar', t.size.icon.toolbar]);
walk(t.radius, ['radius'], (p, v) => shared.push(['--' + p.map(kebab).join('-'), v]));

// shadow: per mode
walk(t.shadow, ['shadow'], (p, v) => {
  const name = '--' + p.map(kebab).join('-');
  light.push([name, v.light]);
  dark.push([name, v.dark]);
});

// motion
walk(t.motion, ['motion'], (p, v) => {
  const name = '--' + p.map(kebab).join('-');
  shared.push([name, Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : v]);
});

const block = (sel, list, indent = '') =>
  `${indent}${sel} {\n${list.map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}\n`;

const css = `/* GENERATED by scripts/gen-tokens.mjs from docs/design/tokens.json — do not edit. */
${block(':root', [...shared, ...light])}
${block(':root[data-theme="dark"]', dark)}
@media (prefers-color-scheme: dark) {
${block(':root:not([data-theme="light"])', dark, '  ')}}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css: ${shared.length} shared, ${light.length} light, ${dark.length} dark`);
