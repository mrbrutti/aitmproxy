// Generates src/viewers/lang/defs.gen.ts from docs/design/languages/*.json.
// Those files are the single source of truth for the Rhai grammar/API catalog and the PoC-YAML
// key tree (UI scripting-highlight spec §1.1); the web highlighters and completion sources consume
// this generated module so a keyword, host-function name or PoC key can never be hard-coded on the
// surface (plan "Global Constraints"). Regenerated before dev/test/build, exactly like tokens.css.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const langs = resolve(here, '../../../docs/design/languages');
const out = resolve(here, '../src/viewers/lang/defs.gen.ts');
const confOut = resolve(here, '../src/viewers/lang/conformance.gen.ts');

// Drop the `_comment`/`_*` annotation keys the definition files carry for human readers; they are
// documentation, not data the surface needs.
function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (node && typeof node === 'object') {
    const o = {};
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith('_')) continue;
      o[k] = strip(v);
    }
    return o;
  }
  return node;
}

const read = (name) => strip(JSON.parse(readFileSync(resolve(langs, name), 'utf8')));

const rhaiGrammar = read('rhai.grammar.json');
const rhaiApi = read('rhai.api.json');
const pocSchema = read('poc-yaml.schema.json');

const lit = (v) => JSON.stringify(v, null, 2);

const ts = `// GENERATED by scripts/gen-langs.mjs from docs/design/languages/*.json — do not edit.
// The single source of truth for the Rhai grammar/API catalog and the PoC-YAML key tree; the
// surface's highlighters and completion sources import it so nothing is hard-coded here.

export const rhaiGrammar = ${lit(rhaiGrammar)} as const;

export const rhaiApi = ${lit(rhaiApi)} as const;

export const pocSchema = ${lit(pocSchema)} as const;
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, ts);

// The completion conformance fixtures, emitted as a typed module so the surface's completion tests
// assert against the same shared contract the other surfaces do, without reading files at test time.
const rhaiCompletion = read('rhai.completion.conformance.json');
const pocCompletion = read('poc.completion.conformance.json');
const confTs = `// GENERATED by scripts/gen-langs.mjs from docs/design/languages/*.conformance.json — do not edit.
// The shared completion conformance fixtures (plan Task 2), consumed by the web completion tests.

export interface CompletionFixture {
  name: string;
  context: string;
  caret: number;
  kind: string;
  path: string;
  expected_candidates: string[];
}

export const rhaiCompletionFixtures: CompletionFixture[] = ${lit(rhaiCompletion)};

export const pocCompletionFixtures: CompletionFixture[] = ${lit(pocCompletion)};
`;
writeFileSync(confOut, confTs);

console.log(
  `defs.gen.ts: rhai ${rhaiGrammar.keywords.length} keywords, api ${rhaiApi.hooks.length} hooks + ${rhaiApi.flow.length} flow members, poc ${Object.keys(pocSchema.keys).length} top-level keys`,
);
