#!/usr/bin/env node
// gen-tool-reference.mjs — generate aitmproxy-plugin/docs/tool-reference.md
//
// Node-stdlib only. No network, no npm.
//
// Source of truth (in order of preference):
//   1. the built binary `<repo>/target/debug/aitm --help` (prints the full
//      command catalog — description + params — to stderr, exits non-zero);
//   2. fallback: the saved catalog `<repo>/docs/research/mcp-tool-catalog.txt`.
//
// Each CLI command (`flow list`, `tls passthrough add`, ...) is converted to its
// dot-form MCP tool name (`flow.list`, `tls.passthrough.add`), grouped by
// namespace, with its param signature and one-line description.
//
// Regenerate:
//   node aitmproxy-plugin/scripts/gen-tool-reference.mjs
//
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..", ".."); // aitmproxy-plugin/scripts -> repo root
const binary = resolve(repoRoot, "target", "debug", "aitm");
const catalog = resolve(repoRoot, "docs", "research", "mcp-tool-catalog.txt");
const outFile = resolve(repoRoot, "aitmproxy-plugin", "docs", "tool-reference.md");

// Preferred namespace order (task-specified); unknown namespaces appended after.
const NS_ORDER = [
  "flow", "proxy", "scope", "ws", "map", "browser", "poc", "findings",
  "ca", "agent", "script", "tls.passthrough", "session", "config", "request",
];

function getHelpText() {
  if (existsSync(binary)) {
    try {
      // aitm --help exits non-zero and prints the catalog to stderr.
      execFileSync(binary, ["--help"], { stdio: ["ignore", "ignore", "pipe"] });
      return { text: "", source: "binary" }; // unexpected: no error, no stderr
    } catch (err) {
      const text = (err.stderr || "").toString();
      if (text.includes("commands:")) {
        return { text, source: `binary (\`target/debug/aitm --help\`)` };
      }
    }
  }
  if (existsSync(catalog)) {
    return {
      text: readFileSync(catalog, "utf8"),
      source: "saved catalog (`docs/research/mcp-tool-catalog.txt`) — binary unavailable",
    };
  }
  throw new Error("no source: neither target/debug/aitm nor mcp-tool-catalog.txt found");
}

// Escape a cell for a GitHub-flavoured markdown table.
function cell(s) {
  return s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").trim();
}

function parse(text) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((l) => l.trim() === "commands:");
  const body = start >= 0 ? lines.slice(start + 1) : lines;
  const tools = [];
  let cur = null;
  for (const line of body) {
    const cmd = /^ {2}(\S.*)$/.exec(line); // 2-space indent = command
    const desc = /^ {4,}(\S.*)$/.exec(line); // deeper indent = description
    if (cmd) {
      const tokens = cmd[1].split(/\s+/);
      const words = [];
      let i = 0;
      // Command words are plain lowercase identifiers; flags (`--id`), value
      // placeholders (`<flow-id>`) and optionals (`[--body ...]`) start the params.
      while (i < tokens.length && /^[a-z][a-z0-9_]*$/.test(tokens[i])) {
        words.push(tokens[i]);
        i++;
      }
      if (words.length < 1) continue;
      const params = tokens.slice(i).join(" ");
      const tool = words.join(".");
      const namespace = words.length > 1 ? words.slice(0, -1).join(".") : words[0];
      cur = { tool, namespace, params, desc: "" };
      tools.push(cur);
    } else if (desc && cur) {
      cur.desc = cur.desc ? `${cur.desc} ${desc[1].trim()}` : desc[1].trim();
    }
  }
  return tools;
}

function render(tools, source) {
  const groups = new Map();
  for (const t of tools) {
    if (!groups.has(t.namespace)) groups.set(t.namespace, []);
    groups.get(t.namespace).push(t);
  }
  const ordered = [
    ...NS_ORDER.filter((ns) => groups.has(ns)),
    ...[...groups.keys()].filter((ns) => !NS_ORDER.includes(ns)).sort(),
  ];

  const out = [];
  out.push("# aitmproxy MCP tool reference");
  out.push("");
  out.push(
    "<!-- GENERATED FILE — do not edit by hand. -->",
  );
  out.push(
    "<!-- Regenerate: `node aitmproxy-plugin/scripts/gen-tool-reference.mjs` -->",
  );
  out.push("");
  out.push(
    "This reference is generated by `aitmproxy-plugin/scripts/gen-tool-reference.mjs`",
  );
  out.push(`from the ${source}.`);
  out.push("");
  out.push(
    "Tool names are shown in dot form (`flow.list`), as the MCP server exposes them;",
  );
  out.push(
    "the `aitm` CLI accepts the same commands space-separated (`aitm flow list`).",
  );
  out.push("");
  out.push(`**${tools.length} tools across ${ordered.length} namespaces.**`);
  out.push("");

  for (const ns of ordered) {
    out.push(`## \`${ns}.*\``);
    out.push("");
    out.push("| Tool | Parameters | Description |");
    out.push("| --- | --- | --- |");
    for (const t of groups.get(ns)) {
      const params = t.params ? `\`${cell(t.params)}\`` : "—";
      out.push(`| \`${t.tool}\` | ${params} | ${cell(t.desc) || "—"} |`);
    }
    out.push("");
  }
  return out.join("\n");
}

const { text, source } = getHelpText();
const tools = parse(text);
if (tools.length === 0) {
  console.error("error: parsed 0 tools from source");
  process.exit(1);
}
const md = render(tools, source);
writeFileSync(outFile, md);
console.log(`wrote ${outFile}`);
console.log(`source: ${source}`);
console.log(`tools:  ${tools.length}`);
