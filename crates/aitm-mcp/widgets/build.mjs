// Generates tokens.css from docs/design/tokens.json.
//
// tokens.json is the single source of truth (docs/design/operator-ui-foundation.md §2).
// This generator is the MCP-widget surface's mapping of its palette: a :root block holds
// the light colour values plus the font families/weights; the dark colour values are
// emitted twice — under [data-theme="dark"] (explicit theme pin) and inside
// @media (prefers-color-scheme: dark) (host default) — so every widget that pastes this
// file is correct in both modes without JS.
//
// The emitted tokens.css is COMMITTED so the Rust build never needs Node; regenerating is
// a documented developer step (see README.md). Node stdlib only — no npm, no download.
//
// Run:  node crates/aitm-mcp/widgets/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../../docs/design/tokens.json');
const out = resolve(here, 'tokens.css');
const t = JSON.parse(readFileSync(src, 'utf8'));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const isToken = (n) => n && typeof n === 'object' && '$value' in n;

function walk(node, path, fn) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (isToken(v)) fn([...path, k], v.$value);
    else if (v && typeof v === 'object') walk(v, [...path, k], fn);
  }
}

const shared = []; // mode-independent (fonts)
const light = [];
const dark = [];

// --color-<group>-<name>[-fg|-bg], one declaration per mode.
walk(t.color, ['color'], (p, v) => {
  const name = '--' + p.map(kebab).join('-');
  const emit = (mode, list) => {
    const m = v[mode];
    if (typeof m === 'string') list.push([name, m]);
    else {
      list.push([`${name}-fg`, m.fg]);
      list.push([`${name}-bg`, m.bg]);
    }
  };
  emit('light', light);
  emit('dark', dark);
});

// Font families (--font-ui, --font-data) and weights (--font-weight-*): mode-independent.
for (const [k, v] of Object.entries(t.typography.family)) {
  if (k.startsWith('$')) continue;
  shared.push([`--font-${kebab(k)}`, v.$value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ')]);
}
walk(t.typography.weight, ['font-weight'], (p, v) =>
  shared.push(['--' + p.map(kebab).join('-'), String(v)]),
);

const block = (sel, list, indent = '') =>
  `${indent}${sel} {\n${list.map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}\n`;

const css = `/* GENERATED by build.mjs from docs/design/tokens.json — do not edit by hand. */
/* Regenerate: node crates/aitm-mcp/widgets/build.mjs (see README.md). */
${block(':root', [...shared, ...light])}
${block('[data-theme="dark"]', dark)}
@media (prefers-color-scheme: dark) {
${block(':root:not([data-theme="light"])', dark, '  ')}}
`;

writeFileSync(out, css);
console.log(`tokens.css: ${shared.length} shared, ${light.length} light, ${dark.length} dark`);
