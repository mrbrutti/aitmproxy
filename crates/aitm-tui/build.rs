//! Build script: generates `$OUT_DIR/tokens.rs` from `docs/design/tokens.json`.
//!
//! The JSON is the W3C design-tokens file shared with the macOS app and the
//! web UI (`docs/design/operator-ui-foundation.md` §2.2–§2.5, §2.10(c)). This
//! script turns `color.*` into `ColorToken`/`PairToken` constants,
//! `icon.glyph.*.tui` into `glyph::*` strings, and keeps the one size token
//! the terminal needs (the 28-column sidebar). Any shape it does not
//! understand is a build failure: a silently dropped token would be worse.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

/// Path of the tokens file relative to this crate's manifest directory.
const TOKENS_REL: &str = "../../docs/design/tokens.json";

/// Directory of the shared language definitions (UI-ext spec §1.1), relative
/// to this crate's manifest directory. The highlighter's keyword set and the
/// completion catalogs are generated from these, exactly as `tokens.rs` is
/// generated from `tokens.json`.
const LANGS_REL: &str = "../../docs/design/languages";

/// Fixed sidebar width in terminal columns (§2.4: "28 columns for the sidebar").
const SIDEBAR_COLS: u16 = 28;

fn main() {
    println!("cargo:rerun-if-changed={TOKENS_REL}");
    println!("cargo:rerun-if-changed=build.rs");
    for f in ["rhai.grammar.json", "rhai.api.json", "poc-yaml.schema.json"] {
        println!("cargo:rerun-if-changed={LANGS_REL}/{f}");
    }

    let manifest_dir = env_path("CARGO_MANIFEST_DIR");
    let tokens_path = manifest_dir.join(TOKENS_REL);
    let root = read_tokens(&tokens_path);

    let generated = generate(&root);

    let out_path = env_path("OUT_DIR").join("tokens.rs");
    if let Err(e) = std::fs::write(&out_path, generated) {
        panic!("tokens: cannot write {}: {e}", out_path.display());
    }

    let langs = generate_languages(&manifest_dir.join(LANGS_REL));
    let langs_path = env_path("OUT_DIR").join("languages.rs");
    if let Err(e) = std::fs::write(&langs_path, langs) {
        panic!("languages: cannot write {}: {e}", langs_path.display());
    }
}

/// Generates `languages.rs`: the Rhai keyword/literal sets for the tokenizer
/// and the embedded completion catalogs, from the shared definition files.
/// A missing or malformed file fails the build — the TUI is pinned to the
/// shared defs, so it cannot silently drift from the web and macOS surfaces.
fn generate_languages(dir: &Path) -> String {
    let grammar = read_language_json(&dir.join("rhai.grammar.json"));
    let api_raw = read_language_text(&dir.join("rhai.api.json"));
    let schema_raw = read_language_text(&dir.join("poc-yaml.schema.json"));
    // Parse-check the catalogs here so a broken def fails the build, not a test.
    if let Err(e) = serde_json::from_str::<Value>(&api_raw) {
        panic!("languages: rhai.api.json is not valid JSON: {e}");
    }
    if let Err(e) = serde_json::from_str::<Value>(&schema_raw) {
        panic!("languages: poc-yaml.schema.json is not valid JSON: {e}");
    }

    let keywords = string_array(&grammar, "keywords");
    let literals = string_array(&grammar, "literals");

    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by crates/aitm-tui/build.rs from docs/design/languages/. Do not edit."
    );
    write_str_slice(
        &mut out,
        "RHAI_KEYWORDS",
        "Rhai control words (`rhai.grammar.json`), coloured as keywords.",
        &keywords,
    );
    write_str_slice(
        &mut out,
        "RHAI_LITERALS",
        "Rhai literals (`true`/`false`/`()`), coloured as booleans.",
        &literals,
    );
    let _ = writeln!(
        out,
        "/// The embedded `rhai.api.json` completion + hover catalog."
    );
    let _ = writeln!(out, "pub const RHAI_API_JSON: &str = {api_raw:?};");
    let _ = writeln!(
        out,
        "/// The embedded `poc-yaml.schema.json` key tree for completion."
    );
    let _ = writeln!(out, "pub const POC_SCHEMA_JSON: &str = {schema_raw:?};");
    out
}

/// Reads and parses one language definition file, failing the build clearly.
fn read_language_json(path: &Path) -> Map<String, Value> {
    match serde_json::from_str::<Value>(&read_language_text(path)) {
        Ok(Value::Object(m)) => m,
        Ok(_) => panic!("languages: {} must be a JSON object", path.display()),
        Err(e) => panic!("languages: {} is not valid JSON: {e}", path.display()),
    }
}

/// Reads one language definition file's text, failing the build clearly.
fn read_language_text(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| {
        panic!(
            "languages: cannot read {} ({e}); the TUI is generated from docs/design/languages/",
            path.display()
        )
    })
}

/// A string array field (e.g. `keywords`) from a definition object.
fn string_array(obj: &Map<String, Value>, key: &str) -> Vec<String> {
    match obj.get(key) {
        Some(Value::Array(a)) => a
            .iter()
            .map(|v| match v {
                Value::String(s) => s.clone(),
                other => panic!("languages: {key}[] has a non-string entry {other}"),
            })
            .collect(),
        _ => panic!("languages: missing string array {key:?}"),
    }
}

/// Emits `pub const NAME: &[&str] = &[…];` with a doc line.
fn write_str_slice(out: &mut String, name: &str, doc: &str, items: &[String]) {
    let _ = writeln!(out, "/// {doc}");
    let _ = write!(out, "pub const {name}: &[&str] = &[");
    for (i, s) in items.iter().enumerate() {
        if i > 0 {
            let _ = write!(out, ", ");
        }
        let _ = write!(out, "{s:?}");
    }
    let _ = writeln!(out, "];");
}

/// Reads an environment variable Cargo always sets for build scripts.
fn env_path(var: &str) -> PathBuf {
    match std::env::var_os(var) {
        Some(v) => PathBuf::from(v),
        None => panic!("tokens: {var} is not set; this program must run as a Cargo build script"),
    }
}

/// Loads and parses the tokens file, failing the build with a clear message.
fn read_tokens(path: &Path) -> Map<String, Value> {
    let text = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(e) => panic!(
            "tokens: cannot read {} ({e}); the TUI is generated from docs/design/tokens.json",
            path.display()
        ),
    };
    match serde_json::from_str::<Value>(&text) {
        Ok(Value::Object(map)) => map,
        Ok(_) => panic!(
            "tokens: {} must be a JSON object at the top level",
            path.display()
        ),
        Err(e) => panic!("tokens: {} is not valid JSON: {e}", path.display()),
    }
}

/// A single light/dark colour token.
struct ColorDef {
    /// Dotted token path, e.g. `ground.page`.
    path: String,
    /// Rust constant name, e.g. `PAGE`.
    name: String,
    light: Rgb,
    dark: Rgb,
    ansi: Option<String>,
}

/// A `{fg, bg}` pair token (badges, pills, diff lines).
struct PairDef {
    path: String,
    name: String,
    light: (Rgb, Rgb),
    dark: (Rgb, Rgb),
    ansi: Option<String>,
}

/// One `color.<group>` module's worth of tokens.
struct Group {
    name: String,
    colors: Vec<ColorDef>,
    pairs: Vec<PairDef>,
}

#[derive(Clone, Copy)]
struct Rgb(u8, u8, u8);

/// Produces the full text of the generated `tokens.rs`.
fn generate(root: &Map<String, Value>) -> String {
    let version = match root.get("$version") {
        Some(Value::String(v)) => v.clone(),
        _ => panic!("tokens: missing or non-string \"$version\" at the top level"),
    };

    let groups = collect_groups(root);
    let glyphs = collect_glyphs(root);

    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by crates/aitm-tui/build.rs from docs/design/tokens.json (v{version}). Do not edit."
    );
    out.push_str(PRELUDE);
    let _ = writeln!(
        out,
        "/// The `$version` of the tokens file this build was generated from."
    );
    let _ = writeln!(out, "pub const TOKENS_VERSION: &str = {version:?};\n");

    write_color_mod(&mut out, &groups);
    write_glyph_mod(&mut out, &glyphs);
    write_size_mod(&mut out);
    write_tables(&mut out, &groups);
    out
}

/// Type definitions shared by every generated constant.
const PRELUDE: &str = r#"
/// An sRGB triple parsed from a `#RRGGBB` token value.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Rgb(pub u8, pub u8, pub u8);

/// A colour token with one value per appearance and an optional ANSI-16 name
/// for terminals without truecolor.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ColorToken {
    /// The light-mode value (unused by the TUI, kept for parity).
    pub light: Rgb,
    /// The dark-mode value; what truecolor terminals render.
    pub dark: Rgb,
    /// The `tui` ANSI colour name, when the token defines one.
    pub ansi: Option<&'static str>,
}

/// A foreground/background pair token (badges, pills, diff lines).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PairToken {
    /// Light-mode text colour.
    pub light_fg: Rgb,
    /// Light-mode fill.
    pub light_bg: Rgb,
    /// Dark-mode text colour; what truecolor terminals render.
    pub dark_fg: Rgb,
    /// Dark-mode fill; what truecolor terminals render.
    pub dark_bg: Rgb,
    /// The `tui` ANSI colour name, when the token defines one.
    pub ansi: Option<&'static str>,
}

"#;

/// Walks `color.<group>.<token>` and classifies every token.
///
/// Order: `serde_json::Map` without `preserve_order` is a `BTreeMap`, so the
/// generated groups, constants and `ALL_*` tables are alphabetical by key,
/// not in file order. The same holds for `collect_glyphs`.
fn collect_groups(root: &Map<String, Value>) -> Vec<Group> {
    let color = match root.get("color") {
        Some(Value::Object(m)) => m,
        _ => panic!("tokens: missing \"color\" object"),
    };

    let mut groups = Vec::new();
    for (group_name, group_val) in color.iter().filter(|(k, _)| !is_meta(k)) {
        let Value::Object(entries) = group_val else {
            panic!("tokens: color.{group_name} must be an object");
        };
        let mut group = Group {
            name: group_name.clone(),
            colors: Vec::new(),
            pairs: Vec::new(),
        };
        for (token_name, token_val) in entries.iter().filter(|(k, _)| !is_meta(k)) {
            let path = format!("{group_name}.{token_name}");
            let Value::Object(token) = token_val else {
                panic!("tokens: color.{path} must be an object");
            };
            let Some(Value::Object(value)) = token.get("$value") else {
                panic!("tokens: color.{path} has no \"$value\" object");
            };
            let ansi = match token.get("tui") {
                None => None,
                Some(Value::String(s)) => Some(s.clone()),
                Some(_) => panic!("tokens: color.{path}.tui must be a string"),
            };
            let name = screaming_snake(token_name);
            match (value.get("light"), value.get("dark")) {
                (Some(Value::String(l)), Some(Value::String(d))) => group.colors.push(ColorDef {
                    light: parse_hex(l, &path),
                    dark: parse_hex(d, &path),
                    path,
                    name,
                    ansi,
                }),
                (Some(Value::Object(l)), Some(Value::Object(d))) => group.pairs.push(PairDef {
                    light: parse_pair(l, &path),
                    dark: parse_pair(d, &path),
                    path,
                    name,
                    ansi,
                }),
                _ => panic!(
                    "tokens: color.{path}.$value needs \"light\" and \"dark\" that are both hex strings or both {{fg,bg}} objects"
                ),
            }
        }
        groups.push(group);
    }
    groups
}

/// Reads `{fg, bg}` from one side of a pair token.
fn parse_pair(side: &Map<String, Value>, path: &str) -> (Rgb, Rgb) {
    let get = |key: &str| match side.get(key) {
        Some(Value::String(s)) => parse_hex(s, path),
        _ => panic!("tokens: color.{path} pair value is missing a \"{key}\" hex string"),
    };
    (get("fg"), get("bg"))
}

/// Parses exactly `#RRGGBB`; anything else fails the build.
fn parse_hex(s: &str, path: &str) -> Rgb {
    let bad = || panic!("tokens: color.{path} value {s:?} is not of the form #RRGGBB");
    let Some(hex) = s.strip_prefix('#') else {
        bad()
    };
    if hex.len() != 6 || !hex.bytes().all(|b| b.is_ascii_hexdigit()) {
        bad();
    }
    let channel = |i: usize| u8::from_str_radix(&hex[i..i + 2], 16).unwrap_or_else(|_| bad());
    Rgb(channel(0), channel(2), channel(4))
}

/// Walks `icon.glyph.*` and returns `(NAME, tui-string)` pairs.
fn collect_glyphs(root: &Map<String, Value>) -> Vec<(String, String)> {
    let glyphs = match root.get("icon").and_then(|i| i.get("glyph")) {
        Some(Value::Object(m)) => m,
        _ => panic!("tokens: missing \"icon.glyph\" object"),
    };
    glyphs
        .iter()
        .filter(|(k, _)| !is_meta(k))
        .map(|(name, val)| match val.get("tui") {
            Some(Value::String(s)) => (screaming_snake(name), s.clone()),
            _ => panic!("tokens: icon.glyph.{name} has no \"tui\" string"),
        })
        .collect()
}

/// `$`-prefixed keys are W3C metadata (`$type`, `$value`, `$description`).
fn is_meta(key: &str) -> bool {
    key.starts_with('$')
}

/// `onAccent` → `ON_ACCENT`, `lineNumber` → `LINE_NUMBER`, `get` → `GET`.
/// A name that starts with a digit cannot be a Rust identifier and fails the
/// build with a message naming it.
fn screaming_snake(name: &str) -> String {
    if name.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        panic!(
            "tokens: {name:?} starts with a digit and cannot be a Rust constant name; rename the token (e.g. prefix a letter)"
        );
    }
    let mut out = String::with_capacity(name.len() + 4);
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() && i > 0 {
            out.push('_');
        }
        match ch {
            'a'..='z' | 'A'..='Z' | '0'..='9' => out.push(ch.to_ascii_uppercase()),
            '-' | '.' => out.push('_'),
            other => {
                panic!("tokens: cannot turn {name:?} into a Rust identifier (bad char {other:?})")
            }
        }
    }
    out
}

fn rgb_lit(c: Rgb) -> String {
    format!("Rgb(0x{:02X}, 0x{:02X}, 0x{:02X})", c.0, c.1, c.2)
}

fn ansi_lit(ansi: &Option<String>) -> String {
    match ansi {
        Some(s) => format!("Some({s:?})"),
        None => "None".to_string(),
    }
}

fn write_color_mod(out: &mut String, groups: &[Group]) {
    let _ = writeln!(
        out,
        "/// Colour tokens, one submodule per `color.<group>` in tokens.json."
    );
    let _ = writeln!(out, "pub mod color {{");
    for g in groups {
        let _ = writeln!(out, "    /// `color.{}` tokens.", g.name);
        let _ = writeln!(out, "    pub mod {} {{", g.name);
        let mut imports = vec!["Rgb"];
        if !g.colors.is_empty() {
            imports.push("ColorToken");
        }
        if !g.pairs.is_empty() {
            imports.push("PairToken");
        }
        let _ = writeln!(
            out,
            "        use super::super::{{{}}};\n",
            imports.join(", ")
        );
        for c in &g.colors {
            let _ = writeln!(out, "        /// `color.{}`", c.path);
            let _ = writeln!(
                out,
                "        pub const {}: ColorToken = ColorToken {{ light: {}, dark: {}, ansi: {} }};",
                c.name,
                rgb_lit(c.light),
                rgb_lit(c.dark),
                ansi_lit(&c.ansi)
            );
        }
        for p in &g.pairs {
            let _ = writeln!(out, "        /// `color.{}` (fg on bg)", p.path);
            let _ = writeln!(
                out,
                "        pub const {}: PairToken = PairToken {{ light_fg: {}, light_bg: {}, dark_fg: {}, dark_bg: {}, ansi: {} }};",
                p.name,
                rgb_lit(p.light.0),
                rgb_lit(p.light.1),
                rgb_lit(p.dark.0),
                rgb_lit(p.dark.1),
                ansi_lit(&p.ansi)
            );
        }
        let _ = writeln!(out, "    }}\n");
    }
    let _ = writeln!(out, "}}\n");
}

fn write_glyph_mod(out: &mut String, glyphs: &[(String, String)]) {
    let _ = writeln!(
        out,
        "/// Terminal glyphs: the `tui` string of every `icon.glyph.*` role."
    );
    let _ = writeln!(out, "pub mod glyph {{");
    for (name, s) in glyphs {
        let _ = writeln!(out, "    /// `icon.glyph.{}`", name.to_ascii_lowercase());
        let _ = writeln!(out, "    pub const {name}: &str = {s:?};");
    }
    let _ = writeln!(out, "}}\n");
}

fn write_size_mod(out: &mut String) {
    let _ = writeln!(
        out,
        "/// Shell dimensions in terminal cells. Every other size token collapses to one line (§2.10(c))."
    );
    let _ = writeln!(out, "pub mod size {{");
    let _ = writeln!(
        out,
        "    /// Sidebar width in columns (`size.sidebar`, fixed at 28 for the TUI)."
    );
    let _ = writeln!(out, "    pub const SIDEBAR_COLS: u16 = {SIDEBAR_COLS};");
    let _ = writeln!(out, "}}\n");
}

fn write_tables(out: &mut String, groups: &[Group]) {
    let _ = writeln!(
        out,
        "/// Every single-value colour token as `(\"group.name\", &token)`."
    );
    let _ = writeln!(out, "pub const ALL_COLORS: &[(&str, &ColorToken)] = &[");
    for g in groups {
        for c in &g.colors {
            let _ = writeln!(out, "    ({:?}, &color::{}::{}),", c.path, g.name, c.name);
        }
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(out, "/// Every pair token as `(\"group.name\", &token)`.");
    let _ = writeln!(out, "pub const ALL_PAIRS: &[(&str, &PairToken)] = &[");
    for g in groups {
        for p in &g.pairs {
            let _ = writeln!(out, "    ({:?}, &color::{}::{}),", p.path, g.name, p.name);
        }
    }
    let _ = writeln!(out, "];");
}
